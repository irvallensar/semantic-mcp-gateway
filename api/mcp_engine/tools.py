"""
MCP Tool Executor & Argument Sanitizer:
Converts MCPTool schemas into LLM function definitions, validates arguments against
injection attacks, and executes deterministic sandboxed responses.
"""
import json
from typing import Any, Dict, List, Optional, Tuple
from api.mcp_engine.registry import MCPTool
from core_gateway import PreFlightGuard


class MCPToolExecutor:
    @staticmethod
    def to_openai_tools(mcp_tools: List[MCPTool]) -> List[Dict[str, Any]]:
        """Formats pruned MCPTool schemas into standard OpenAI/Groq tool-calling format."""
        return [
            {
                "type": "function",
                "function": {
                    "name": tool.name,
                    "description": tool.description,
                    "parameters": tool.parameters,
                },
            }
            for tool in mcp_tools
        ]

    @classmethod
    def validate_and_execute(
        cls, tool_name: str, raw_arguments: str
    ) -> Tuple[bool, str, Optional[str]]:
        """
        1. Validates generated tool arguments against PreFlightGuard (blocks SQLi / LFI in tool args).
        2. Executes the sandboxed MCP tool and returns JSON telemetry.
        """
        # Security check on the raw JSON arguments generated by the LLM
        passed, block_reason, _ = PreFlightGuard.inspect(raw_arguments)
        if not passed:
            return False, f"MCP Tool Argument Blocked: {block_reason}", None

        try:
            args = json.loads(raw_arguments) if raw_arguments else {}
        except json.JSONDecodeError:
            args = {"raw": raw_arguments}

        # Simulated deterministic responses for live portfolio demonstration
        mock_responses = {
            "github_list_failing_checks": {
                "status": "failed",
                "branch": args.get("commit_sha", "staging"),
                "failed_job": "unit-tests-py314",
                "error_log": "AssertionError in test_rate_limiter.py:42 - Token bucket drift exceeded 5ms threshold.",
            },
            "sql_inspect_schema": {
                "table": args.get("table_name", "users"),
                "columns": ["id (UUID PK)", "email (VARCHAR UNIQUE)", "created_at (TIMESTAMPTZ)"],
                "missing_index_warning": "Sequential scan detected on 'created_at' (1.2M rows). Recommend B-Tree index.",
            },
            "docker_fetch_logs": {
                "container_id": args.get("container_id", "web-api-prod"),
                "exit_code": 137,
                "stderr_tail": "FATAL: Out of memory (OOMKilled) - container exceeded 512MB cgroup limit during batch embedding.",
            },
            "arxiv_search_papers": {
                "query": args.get("query", "speculative decoding"),
                "top_results": [
                    {"id": "2401.15077", "title": "Medusa: Simple LLM Inference Acceleration Framework with Multiple Decoding Heads"},
                    {"id": "2302.01318", "title": "Accelerating Large Language Model Decoding with Speculative Sampling"},
                ],
            },
        }

        result_payload = mock_responses.get(
            tool_name,
            {"tool": tool_name, "executed_with_args": args, "status": "200 OK (Sandboxed Execution)"},
        )
        return True, json.dumps(result_payload, indent=2), tool_name